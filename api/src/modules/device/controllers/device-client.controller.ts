import {
  BadRequestException,
  Body,
  Controller,
  ForbiddenException,
  Get,
  Headers,
  HttpCode,
  HttpStatus,
  Ip,
  Post,
  Query,
  UseGuards
} from '@nestjs/common';
import { Throttle, ThrottlerGuard } from '@nestjs/throttler';
import { ApiHeader, ApiOkResponse, ApiOperation, ApiTags } from '@nestjs/swagger';
import { DeviceService } from '../services/device.service';
import { DeviceConfigResponseDto } from '../dto/device-config-response.dto';
import { DeviceMetricsAckDto, DeviceMetricsInputDto } from '../dto/device-metrics-input.dto';
import { ClaimDeviceDto } from '../dto/claim-device.dto';
import { DeviceHelloResponseDto } from '../dto/device-hello-response.dto';
import { ScreensResponseDto } from '../dto/display-profile.dto';
import type { ScreensResponse } from '../screens/screen-composer';
import { TransitStationboardResponseDto } from '../../transit/dto/transit-departure.dto';

@ApiTags('device-client')
// Versioned path: firmware in the field hardcodes these routes, so a breaking change ships as
// api/v2/device alongside this controller instead of replacing it.
@Controller('api/v1/device')
export class DeviceClientController {
  constructor(private readonly deviceService: DeviceService) {}

  @Get('hello')
  @ApiOperation({
    summary: 'Unauthenticated bootstrap info for a device that has not been claimed yet'
  })
  @ApiOkResponse({ type: DeviceHelloResponseDto })
  hello(): DeviceHelloResponseDto {
    return this.deviceService.getHello();
  }

  @Post('claim')
  @UseGuards(ThrottlerGuard)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary:
      "Bind this device's real hardware UUID to a pairing code an admin has already claimed in the UI"
  })
  @ApiOkResponse({ type: DeviceConfigResponseDto })
  async claim(@Body() body: ClaimDeviceDto): Promise<DeviceConfigResponseDto> {
    return this.deviceService.claimDevice(body);
  }

  @Get('config')
  @ApiOperation({ summary: 'Fetch device configuration for ESP32 runner' })
  @ApiHeader({
    name: 'X-Device-ID',
    required: false,
    description: 'Hardware UUID generated by the ESP32 chip'
  })
  @ApiHeader({
    name: 'X-Device-Token',
    required: false,
    description: 'Secret authentication token issued to the device'
  })
  @ApiOkResponse({ type: DeviceConfigResponseDto })
  async getConfig(
    @Headers('x-device-id') headerDeviceId?: string,
    @Headers('x-device-token') headerDeviceToken?: string,
    @Query('deviceId') queryDeviceId?: string,
    @Query('deviceToken') queryDeviceToken?: string,
    @Ip() clientIp?: string
  ): Promise<DeviceConfigResponseDto> {
    const deviceId = headerDeviceId || queryDeviceId;
    if (!deviceId) {
      throw new BadRequestException(
        "Missing required parameter: 'X-Device-ID header or deviceId query'"
      );
    }
    const token = headerDeviceToken || queryDeviceToken;

    const config = await this.deviceService.getDeviceConfig(deviceId, clientIp, token);
    if (!config) {
      // 403 (not 404): the device must keep its token and show "disabled", not fall back to pairing mode.
      throw new ForbiddenException(`Device '${deviceId}' is disabled by its owner`);
    }

    return config;
  }

  @Get('data')
  @ApiOperation({ summary: 'Fetch live transit departures for ESP32 runner' })
  @ApiHeader({
    name: 'X-Device-ID',
    required: false,
    description: 'Hardware UUID generated by the ESP32 chip'
  })
  @ApiHeader({
    name: 'X-Device-Token',
    required: false,
    description: 'Secret authentication token issued to the device'
  })
  @ApiOkResponse({ type: TransitStationboardResponseDto })
  async getData(
    @Headers('x-device-id') headerDeviceId?: string,
    @Headers('x-device-token') headerDeviceToken?: string,
    @Query('deviceId') queryDeviceId?: string,
    @Query('deviceToken') queryDeviceToken?: string,
    @Ip() clientIp?: string
  ): Promise<TransitStationboardResponseDto> {
    const deviceId = headerDeviceId || queryDeviceId || 'default';
    const token = headerDeviceToken || queryDeviceToken;
    return this.deviceService.getDeviceData(deviceId, clientIp, token);
  }

  @Get('screens')
  @ApiOperation({ summary: 'Composed screen pages (widget layout) for the ESP32 renderer' })
  @ApiHeader({ name: 'X-Device-ID', required: true, description: 'Device UUID' })
  @ApiHeader({
    name: 'X-Device-Token',
    required: true,
    description: 'Secret authentication token issued to the device'
  })
  @ApiOkResponse({ type: ScreensResponseDto })
  async getScreens(
    @Headers('x-device-id') deviceId?: string,
    @Headers('x-device-token') token?: string,
    @Ip() clientIp?: string
  ): Promise<ScreensResponse> {
    if (!deviceId) {
      throw new BadRequestException("Missing required parameter: 'X-Device-ID header'");
    }
    return this.deviceService.getDeviceScreens(deviceId, clientIp, token);
  }

  @Post('metrics')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Receive telemetry metrics from ESP32 runner' })
  @ApiHeader({
    name: 'X-Device-ID',
    required: false,
    description: 'Hardware UUID generated by the ESP32 chip'
  })
  @ApiHeader({
    name: 'X-Device-Token',
    required: false,
    description: 'Secret authentication token issued to the device'
  })
  @ApiOkResponse({ type: DeviceMetricsAckDto })
  async postMetrics(
    @Body() body: DeviceMetricsInputDto,
    @Headers('x-device-id') headerDeviceId?: string,
    @Headers('x-device-token') headerDeviceToken?: string,
    @Query('deviceToken') queryDeviceToken?: string,
    @Ip() clientIp?: string
  ): Promise<DeviceMetricsAckDto> {
    if (headerDeviceId && !body.deviceId) {
      body.deviceId = headerDeviceId;
    }
    const token = headerDeviceToken || queryDeviceToken;

    await this.deviceService.recordMetrics(body, clientIp, token);
    return { ok: true };
  }
}
