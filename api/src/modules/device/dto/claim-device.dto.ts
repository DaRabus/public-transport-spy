import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString, Matches, MaxLength } from 'class-validator';
import { Transform } from 'class-transformer';
import { normalizePairingCode, PAIRING_CODE_MESSAGE, PAIRING_CODE_PATTERN } from '../pairing-code';

export class ClaimDeviceDto {
  @ApiProperty({
    description:
      'The 6-character pairing code this device generated and is displaying on its own screen.',
    example: 'KV79P2'
  })
  @Transform(({ value }) => normalizePairingCode(value))
  @Matches(PAIRING_CODE_PATTERN, { message: PAIRING_CODE_MESSAGE })
  pairingCode!: string;

  @ApiProperty({
    description:
      'Hardware UUID generated by the ESP32, sent only once an admin has claimed the pairing code.',
    example: 'd3b07384-d113-3660-84cf-3b999cd46903'
  })
  @IsString()
  @IsNotEmpty()
  @MaxLength(64)
  deviceUuid!: string;
}
